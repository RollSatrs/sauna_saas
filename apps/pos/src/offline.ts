/**
 * Работа кассы без интернета.
 *
 * Что можно офлайн: всё, что касается уже начатого визита — добавить товар,
 * продлить, рассчитать, принять наличные. Такие операции копятся в очереди
 * и уходят на сервер, когда связь вернётся.
 *
 * Чего офлайн нельзя и почему:
 *   — новая бронь: непересечение проверяет база, две кассы офлайн запишут
 *     гостей на одно время и узнают об этом слишком поздно;
 *   — списание абонемента: нужен актуальный баланс, иначе спишем дважды;
 *   — оплата картой: банковский терминал сам требует связь.
 *
 * Повтор из очереди безопасен: каждая операция уходит с ключом идемпотентности,
 * и сервер, увидев знакомый ключ, возвращает прежний ответ вместо второй записи.
 */

const БАЗА = "sauna-pos";
const ОЧЕРЕДЬ = "queue";
const КЭШ = "cache";

export type ОперацияВОчереди = {
  id?: number;
  method: string;
  path: string;
  body: unknown;
  key: string;
  описание: string;
  создана: number;
};

/** Что разрешено копить офлайн. Всё остальное офлайн отклоняется с объяснением. */
const РАЗРЕШЕНО: { шаблон: RegExp; метод: string; описание: string }[] = [
  { шаблон: /^\/v1\/visits$/, метод: "POST", описание: "приём гостя" },
  { шаблон: /^\/v1\/visits\/[^/]+\/items$/, метод: "POST", описание: "добавление позиции" },
  { шаблон: /^\/v1\/visits\/[^/]+\/items\/[^/]+$/, метод: "DELETE", описание: "удаление позиции" },
  { шаблон: /^\/v1\/visits\/[^/]+\/extend$/, метод: "POST", описание: "продление" },
  { шаблон: /^\/v1\/visits\/[^/]+\/finish$/, метод: "POST", описание: "расчёт визита" },
  { шаблон: /^\/v1\/orders\/[^/]+\/payments$/, метод: "POST", описание: "оплата" },
  { шаблон: /^\/v1\/shifts\/[^/]+\/cash$/, метод: "POST", описание: "движение наличных" },
];

const ЗАПРЕЩЕНО: { шаблон: RegExp; причина: string }[] = [
  { шаблон: /^\/v1\/bookings/, причина: "Бронь нельзя оформить без связи: программа не сможет проверить, не занято ли это время на другой кассе." },
  { шаблон: /^\/v1\/subscriptions/, причина: "Абонемент без связи недоступен: нужен актуальный остаток, иначе можно списать лишнее." },
  { шаблон: /^\/v1\/manage/, причина: "Настройки меняются только при подключении к интернету." },
  { шаблон: /^\/v1\/customers/, причина: "Нового гостя без связи не завести: карточка должна быть одна на все кассы. Примите его как «аноним», а телефон добавите потом." },
];

export function можноОфлайн(method: string, path: string): { да: boolean; причина?: string; описание?: string } {
  const запрет = ЗАПРЕЩЕНО.find((з) => з.шаблон.test(path));
  if (запрет) return { да: false, причина: запрет.причина };
  const правило = РАЗРЕШЕНО.find((р) => р.метод === method && р.шаблон.test(path));
  if (правило) return { да: true, описание: правило.описание };
  return { да: false, причина: "Эта операция требует связи с сервером." };
}

// ── хранилище ────────────────────────────────────────────────────────────
let соединение: Promise<IDBDatabase> | null = null;

function открыть(): Promise<IDBDatabase> {
  if (соединение) return соединение;
  соединение = new Promise((resolve, reject) => {
    const запрос = indexedDB.open(БАЗА, 1);
    запрос.onupgradeneeded = () => {
      const db = запрос.result;
      if (!db.objectStoreNames.contains(ОЧЕРЕДЬ)) {
        db.createObjectStore(ОЧЕРЕДЬ, { keyPath: "id", autoIncrement: true });
      }
      if (!db.objectStoreNames.contains(КЭШ)) db.createObjectStore(КЭШ);
    };
    запрос.onsuccess = () => resolve(запрос.result);
    запрос.onerror = () => reject(запрос.error);
  });
  return соединение;
}

const транзакция = async <T>(
  хранилище: string, режим: IDBTransactionMode, дело: (s: IDBObjectStore) => IDBRequest<T>,
): Promise<T> => {
  const db = await открыть();
  return new Promise((resolve, reject) => {
    const t = db.transaction(хранилище, режим);
    const запрос = дело(t.objectStore(хранилище));
    запрос.onsuccess = () => resolve(запрос.result);
    запрос.onerror = () => reject(запрос.error);
  });
};

export const очередь = {
  добавить: (о: Omit<ОперацияВОчереди, "id">) =>
    транзакция(ОЧЕРЕДЬ, "readwrite", (s) => s.add(о)),
  все: () => транзакция<ОперацияВОчереди[]>(ОЧЕРЕДЬ, "readonly", (s) => s.getAll()),
  убрать: (id: number) => транзакция(ОЧЕРЕДЬ, "readwrite", (s) => s.delete(id)),
  очистить: () => транзакция(ОЧЕРЕДЬ, "readwrite", (s) => s.clear()),
};

/**
 * Последние ответы сервера на чтения. Офлайн касса показывает их вместо
 * пустого экрана: устаревшие на несколько минут данные лучше, чем ничего.
 * Кэшируем только то, без чего кассир не может работать.
 */
const КЭШИРУЕМ = [
  /^\/v1\/board/,
  /^\/v1\/catalog/,
  /^\/v1\/visits\/[^/]+$/,
  /^\/v1\/orders\/[^/]+$/,
  /^\/v1\/customers/,
];

export const стоитКэшировать = (path: string) => КЭШИРУЕМ.some((r) => r.test(path));

export const снимок = {
  сохранить: (path: string, данные: unknown) =>
    транзакция(КЭШ, "readwrite", (s) => s.put({ данные, когда: Date.now() }, path)),
  прочитать: (path: string) =>
    транзакция<{ данные: unknown; когда: number } | undefined>(КЭШ, "readonly", (s) => s.get(path)),
};

// ── отправка накопленного ────────────────────────────────────────────────
export type Итог = { отправлено: number; осталось: number; ошибки: string[] };

/**
 * Отправляет очередь по порядку. Порядок важен: позиция должна уйти раньше
 * расчёта, а расчёт — раньше оплаты. На сетевой ошибке останавливаемся
 * и ждём следующей попытки; на отказе сервера убираем операцию и сообщаем.
 */
export async function отправитьНакопленное(
  отправка: (о: ОперацияВОчереди) => Promise<Response>,
): Promise<Итог> {
  const операции = (await очередь.все()).sort((a, b) => (a.id ?? 0) - (b.id ?? 0));
  const ошибки: string[] = [];
  let отправлено = 0;

  for (const о of операции) {
    try {
      const ответ = await отправка(о);
      if (ответ.ok) {
        await очередь.убрать(о.id!);
        отправлено++;
        continue;
      }
      if (ответ.status >= 400 && ответ.status < 500) {
        // Сервер отказал по существу — повторять бессмысленно.
        const тело = await ответ.json().catch(() => ({}));
        ошибки.push(`${о.описание}: ${(тело as { error?: string }).error ?? "отклонено сервером"}`);
        await очередь.убрать(о.id!);
        continue;
      }
      break; // ошибка сервера — попробуем позже
    } catch {
      break; // связи снова нет
    }
  }

  return { отправлено, осталось: (await очередь.все()).length, ошибки };
}

/** Подписка на появление и пропадание связи. */
export function следитьЗаСвязью(изменилось: (наСвязи: boolean) => void): () => void {
  const включили = () => изменилось(true);
  const выключили = () => изменилось(false);
  window.addEventListener("online", включили);
  window.addEventListener("offline", выключили);
  return () => {
    window.removeEventListener("online", включили);
    window.removeEventListener("offline", выключили);
  };
}
