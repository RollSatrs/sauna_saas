-- Как считать визит, если он переходит из одного тарифа в другой. По умолчанию —
-- посегментно (наше преимущество перед Paloma, у которой выбора нет вовсе).
-- Первому клиенту нужен режим «по времени входа»: весь визит по тарифу,
-- действовавшему в момент старта. Оставляем настройкой услуги, а не убираем
-- посегментный расчёт — у следующих заведений может быть другое требование.
ALTER TABLE services
  ADD COLUMN time_pricing_mode text NOT NULL DEFAULT 'segments'
    CHECK (time_pricing_mode IN ('segments', 'at_start'));
