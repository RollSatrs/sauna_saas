-- Конец суток записывался как 23:59:59, а тариф действует «до, но не включая».
-- Из-за этого последняя минута суток оставалась без тарифа, и визит,
-- заканчивающийся в 23:59, невозможно было рассчитать.
-- PostgreSQL умеет хранить время 24:00:00 — им и пользуемся.
UPDATE price_rules SET time_to = '24:00:00' WHERE time_to = '23:59:59';
